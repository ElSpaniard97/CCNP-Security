"""Refresh per-chapter flashcards, search index and versioned offline asset list.
Run after changing site assets or study data. --check checks drift without writing.
"""
import hashlib
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def generated():
    cards = json.loads((ROOT / 'data/flashcards.json').read_text())
    output = {}
    for chapter, deck in cards.items():
        output[f'data/flashcards/ch{int(chapter):02}.json'] = json.dumps(deck, ensure_ascii=False, separators=(',', ':')) + '\n'
    output['data/search-index.json'] = json.dumps([[int(n), c['front']] for n, deck in cards.items() for c in deck], ensure_ascii=False, separators=(',', ':')) + '\n'
    return output

def main():
    output = generated()
    shell = ['index.html', 'manifest.webmanifest', 'data/chapters.json', 'data/blueprint.json'] + sorted(str(p.relative_to(ROOT)) for p in (ROOT / 'assets').rglob('*') if p.is_file())
    data = ['data/search-index.json'] + sorted(output.keys() - {'data/search-index.json'}) + sorted(str(p.relative_to(ROOT)) for p in (ROOT / 'data/tests').glob('ch*.json'))
    digest = hashlib.sha256()
    for name in shell + data + ['sw.js']:
        digest.update(name.encode())
        digest.update(output[name].encode() if name in output else (ROOT / name).read_bytes())
    output['offline-assets.js'] = '// Generated by tools/build_site_data.py; do not edit.\nself.OFFLINE_ASSETS = ' + json.dumps({'version': digest.hexdigest()[:16], 'shell': shell, 'data': data}, separators=(',', ':')) + ';\n'
    bad = []
    for name, text in output.items():
        path = ROOT / name
        if '--check' in sys.argv:
            if not path.exists() or path.read_text() != text:
                bad.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if bad:
        sys.exit('Generated data out of date: ' + ', '.join(bad) + '. Run python3 tools/build_site_data.py')
    print('Generated site data is current.' if '--check' in sys.argv else 'Updated chapter flashcards, search index and offline version.')

if __name__ == '__main__':
    main()
